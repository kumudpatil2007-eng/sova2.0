import jsPDF from 'jspdf';

export function exportToPdf(title: string = 'Engineering Note', markdownContent?: string) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const margin = 20;
  const pageWidth = 210 - margin * 2;
  let y = margin;

  const addLine = (text: string, fontSize: number, isBold = false, color: [number, number, number] = [30, 41, 59]) => {
    doc.setFontSize(fontSize);
    doc.setFont('helvetica', isBold ? 'bold' : 'normal');
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(text, pageWidth);
    lines.forEach((line: string) => {
      if (y > 270) {
        doc.addPage();
        y = margin;
      }
      doc.text(line, margin, y);
      y += fontSize * 0.45;
    });
    y += 2;
  };

  const addSpacer = (h = 4) => { y += h; };

  // Header
  addLine(title, 14, true, [37, 99, 235]);
  addSpacer(2);
  addLine(`Generated locally by SOVA on ${new Date().toLocaleDateString()}`, 9, false, [100, 116, 139]);
  addSpacer(2);

  // Horizontal rule
  doc.setDrawColor(226, 232, 240);
  doc.line(margin, y, 210 - margin, y);
  y += 6;

  // Process markdown lines
  const lines = (markdownContent || 'No content provided.').split('\n');
  for (const line of lines) {
    if (line.startsWith('# ')) {
      addSpacer(3);
      addLine(line.replace('# ', ''), 13, true, [15, 23, 42]);
    } else if (line.startsWith('## ')) {
      addSpacer(2);
      addLine(line.replace('## ', ''), 11, true, [37, 99, 235]);
    } else if (line.startsWith('### ')) {
      addLine(line.replace('### ', ''), 10, true, [51, 65, 85]);
    } else if (line.trim().startsWith('- ') || line.trim().startsWith('* ')) {
      addLine(`• ${line.trim().substring(2)}`, 9.5, false);
    } else if (line.trim()) {
      addLine(line.trim(), 9.5, false);
    } else {
      addSpacer(2);
    }
  }

  // Footer
  addSpacer(8);
  doc.setDrawColor(226, 232, 240);
  doc.line(margin, y, 210 - margin, y);
  y += 5;
  addLine('Generated by SOVA — Air-Gapped Local Engineering AI', 8, false, [148, 163, 184]);
  addLine('100% on-premise execution with zero external data egress.', 8, false, [148, 163, 184]);

  doc.save(`${title.replace(/[^a-zA-Z0-9_-]/g, '_')}.pdf`);
}
